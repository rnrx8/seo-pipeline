def intent_value_context(chains):
    """Keep existing analysis links, not just a catchy phrase. No new AI call."""
    if not isinstance(chains, list):
        return []
    keys = ('origin', 'direction', 'trace', 'concrete_phrase', 'serp_grounded')
    return [{k: c[k] for k in keys if k in c}
            for c in chains if isinstance(c, dict)
            and any(c.get(k) for k in ('origin', 'trace', 'concrete_phrase'))]


def intent_value_prompt(chains):
    import json
    context = intent_value_context(chains)
    if not context:
        return ''
    return ('\n【検索意図チェーン：読者の望みと葛藤、推奨理由への接続】\n'
            '以下は読者理解の仮説で、実際の発言・統計・商材の実証済み成果ではない。'
            'originとtraceを保って確認済みの強みと結び付け、単なる便利さから一歩深い価値を伝える。'
            '具体的な言葉は原文を活かしてよい。含まれる数値・事実は確認済み情報と一致させ、'
            '感情表現や守りたいものへの共感は維持する。\n'
            + json.dumps(context, ensure_ascii=False) + '\n')
